#!/usr/bin/env node
// Dev-only: seeds a household on LOCAL Supabase for a two-simulator run
// of group Help Me Choose — Alex, Blair and Casey, joined through the
// real invitation RPCs, with a recipe library. Reuses the e2e fixture,
// which refuses any non-loopback host.
//
// Credentials go to supabase/.temp/group-test-accounts (gitignored, and
// not a root .env* file, which Expo's bundler pulls into the graph) and
// are never printed. scripts/run-sim-pair.sh reads them to give each
// simulator its own Metro server with that member's dev auto sign-in.
//
// Usage: node scripts/seed-local-group-household.mjs

import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { localSupabaseConfig, seedHousehold } from '../supabase/tests/e2e/fixture.mjs';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(rootDir, 'supabase', '.temp', 'group-test-accounts');

const config = localSupabaseConfig();
const { members } = await seedHousehold(config, { memberNames: ['Alex', 'Blair', 'Casey'] });

const lines = ['# Generated by scripts/seed-local-group-household.mjs — local Supabase only.'];
for (const member of Object.values(members)) {
  const key = member.name.toUpperCase();
  lines.push(`GROUP_TEST_${key}_EMAIL=${member.email}`);
  lines.push(`GROUP_TEST_${key}_PASSWORD=${member.password}`);
}
mkdirSync(path.dirname(outputPath), { recursive: true });
writeFileSync(outputPath, `${lines.join('\n')}\n`, { mode: 0o600 });

console.log(`Seeded ${Object.keys(members).join(', ')} into one local household.`);
console.log(`Credentials written to ${path.relative(rootDir, outputPath)}.`);
